def train_ml_models():
    np.random.seed(42)
    n_samples = 3000
    data = {
        'hour': np.random.randint(0, 24, n_samples),
        'day_of_week': np.random.randint(0, 7, n_samples),
        'is_weekend': np.random.choice([0, 1], n_samples),
        'precipitation': np.random.uniform(0, 10, n_samples),
        'traffic_level': np.random.uniform(1.0, 3.0, n_samples),
        'roadworks_density': np.random.uniform(0.0, 1.0, n_samples),
        'temperature': np.random.uniform(-10, 35, n_samples),
        'event_factor': np.random.choice([0, 1], n_samples, p=[0.8, 0.2]),
        'lat': np.random.uniform(41.80, 41.85, n_samples),
        'lng': np.random.uniform(-87.83, -87.78, n_samples),
    }
    df = pd.DataFrame(data)

    raw_risk = (
        (df['hour'] >= 18) * 1.5 +
        (df['precipitation'] > 3) * 1.3 +
        (df['traffic_level'] > 1.5) * 1.2 +
        np.random.uniform(0.1, 0.4, n_samples)
    )
    df['incident_risk'] = np.random.poisson(lam=raw_risk)

    features = [
        'hour', 'day_of_week', 'is_weekend', 'precipitation',
        'traffic_level', 'roadworks_density', 'temperature', 'event_factor',
        'lat', 'lng'
    ]

    models = {
        'Poisson Regression (Rare Events)': PoissonRegressor(max_iter=300),
        'XGBoost Regressor': xgb.XGBRegressor(n_estimators=50, random_state=42, verbosity=0),
        'LightGBM Regressor': lgb.LGBMRegressor(n_estimators=50, random_state=42, verbose=-1),
        'Random Forest': RandomForestRegressor(n_estimators=50, random_state=42),
        'Gradient Boosting': GradientBoostingRegressor(n_estimators=50, random_state=42),
        'Linear Regression': LinearRegression()
    }

    for name, model in models.items():
        model.fit(df[features], df['incident_risk'])

    return models, features

trained_models, feature_names = train_ml_models()

