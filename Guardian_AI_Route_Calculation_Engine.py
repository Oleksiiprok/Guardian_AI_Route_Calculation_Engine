    k_total = car_slider.value
    opt_pos_before = state['opt_positions']
    selected_algo = algo_drop.value

    risk_df = state['risk_df']
    probabilities = risk_df['predicted_risk'] / risk_df['predicted_risk'].sum()
    selected_row = risk_df.sample(1, weights=probabilities).iloc[0]
    incident = int(selected_row['node_id'])

