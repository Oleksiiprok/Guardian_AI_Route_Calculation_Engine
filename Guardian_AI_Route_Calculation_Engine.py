def compute_route_with_detour(G, start_node, target_node, traffic_factor):
    """
    UA: Обчислює основний та об'їзний маршрути у разі критичних заторів (>2.0x).
    EN: Computes direct and detour routes when critical traffic (>2.0x) is detected.
    """
    # 1. Standard traffic-adjusted weights
    for u, v, k, data in G.edges(keys=True, data=True):
        base_t = data.get('travel_time', 10.0)
        data['live_weight'] = base_t * traffic_factor

    direct_path = nx.shortest_path(G, start_node, target_node, weight='live_weight')
    direct_eta = nx.shortest_path_length(G, start_node, target_node, weight='live_weight')

    # 2. Check if critical congestion triggers a detour requirement
    if traffic_factor > 2.0:
        # Penalize main congested corridor edges to force alternative route finding
        G_temp = G.copy()
        for i in range(len(direct_path) - 1):
            u, v = direct_path[i], direct_path[i+1]
            if G_temp.has_edge(u, v):
                for k in G_temp[u][v]:
                    G_temp[u][v][k]['detour_weight'] = G_temp[u][v][k]['live_weight'] * 4.0

        for u, v, k, data in G_temp.edges(keys=True, data=True):
            if 'detour_weight' not in data:
                data['detour_weight'] = data['live_weight']

        try:
            detour_path = nx.shortest_path(G_temp, start_node, target_node, weight='detour_weight')
            detour_eta = nx.shortest_path_length(G_temp, start_node, target_node, weight='live_weight')
            return direct_path, direct_eta, detour_path, detour_eta, True
        except nx.NetworkXNoPath:
            pass

    return direct_path, direct_eta, None, None, False

