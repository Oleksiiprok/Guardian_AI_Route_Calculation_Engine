def find_weighted_clusters(G, k, context, selected_algo):
    nodes_gdf = ox.graph_to_gdfs(G, edges=False)
    df_nodes = pd.DataFrame({
        'node_id': nodes_gdf.index,
        'lat': nodes_gdf.geometry.y,
        'lng': nodes_gdf.geometry.x,
        'hour': context['hour'],
        'day_of_week': 5,
        'is_weekend': 1,
        'precipitation': context['precipitation'],
        'traffic_level': context['traffic_level'],
        'roadworks_density': context['roadworks_density'],
        'temperature': context['temperature'],
        'event_factor': context['event_factor']
    })

    active_model = trained_models[selected_algo]
    predicted_risk = active_model.predict(df_nodes[feature_names])
    df_nodes['predicted_risk'] = np.clip(predicted_risk, a_min=0.01, a_max=None)

    coords = df_nodes[['lat', 'lng']].values
    weights = df_nodes['predicted_risk'].values

    kmeans = KMeans(n_clusters=k, random_state=42, n_init=5).fit(coords, sample_weight=weights)
    best_nodes = [ox.distance.nearest_nodes(G, lon, lat) for lat, lon in kmeans.cluster_centers_]

    return best_nodes, df_nodes

