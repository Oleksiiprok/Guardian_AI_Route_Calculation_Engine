def fetch_live_weather(lat=41.81, lng=-87.80):
    """UA: Погода через Open-Meteo API. / EN: Weather via Open-Meteo API."""
    try:
        url = f"https://api.open-meteo.com/v1/forecast?latitude={lat}&longitude={lng}&current=temperature_2m,precipitation&timezone=auto"
        res = requests.get(url, timeout=4).json()
        current = res.get('current', {})
        return {
            'temp': float(current.get('temperature_2m', 20.0)),
            'rain': float(current.get('precipitation', 0.0))
        }
    except Exception:
        return {'temp': 20.0, 'rain': 0.0}

def fetch_live_traffic_factor(lat=41.81, lng=-87.80, api_key=TOMTOM_API_KEY):
    """UA: Затори через TomTom API. / EN: Traffic via TomTom API."""
    if api_key == "YOUR_TOMTOM_API_KEY":
        return 2.2  # Default to critical traffic for detour demonstration

    try:
        url = f"https://api.tomtom.com/traffic/services/4/flowSegmentData/relative-delay/10/json?key={api_key}&point={lat},{lng}"
        res = requests.get(url, timeout=4).json()
        flow = res.get('flowSegmentData', {})
        current_speed = flow.get('currentSpeed', 50)
        free_flow_speed = flow.get('freeFlowSpeed', 50)
        return round(max(1.0, free_flow_speed / max(current_speed, 1)), 2)
    except Exception:
        return 2.2

def load_city_data(city_name):
    full_name = f"{city_name}, Illinois, USA"
    if full_name not in city_cache:
        G_raw = ox.graph_from_place(full_name, network_type='drive')
        G = G_raw.subgraph(max(nx.strongly_connected_components(G_raw), key=len)).copy()
        G = ox.add_edge_speeds(G)
        G = ox.add_edge_travel_times(G)
        city_cache[full_name] = G
    return city_cache[full_name]

def get_addr_fast(lat, lng):
    key = (round(lat, 4), round(lng, 4))
    if key not in address_cache:
        try:
            loc = geolocator.reverse((lat, lng), timeout=2)
            address_cache[key] = ", ".join(loc.address.split(',')[:3])
        except:
            address_cache[key] = f"GPS: {lat:.4f}, {lng:.4f}"
    return address_cache[key]

